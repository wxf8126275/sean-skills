#!/usr/bin/env python3
"""
sean_artifact_check.py — 校验产物 catalog 与 state 的一致性。

用法:
  python3 sean_artifact_check.py <project_root> <feature_name> [--json]

检查 5 项:
  1. catalog 存在且可解析
  2. catalog 与 state 的产物路径集合一致
  3. 每个产物文件真实存在于磁盘
  4. 每个产物文件头部有反向引用注释
  5. status / executed / verified 三个维度在两处一致

退出码: 0 = 一致（可能含 warning）, 1 = 有 error

存储兼容：v5 明细在 docs/.sean/features/<name>.json；v4 全量在 docs/.sean/state.json。
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

SECTION_TYPES = {
    "database": "database", "batch": "batch", "config": "config",
    "database artifacts": "database", "batch artifacts": "batch", "config artifacts": "config",
}


def load_feature(root: Path, name: str) -> dict | None:
    """v5: features/<name>.json 优先；v4: 回退到 state.json 全量结构。"""
    detail = root / "docs" / ".sean" / "features" / f"{name}.json"
    if detail.exists():
        try:
            return json.loads(detail.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            print(f"FAIL: {detail} 解析失败: {exc}", file=sys.stderr)
            raise SystemExit(1)
    state_path = root / "docs" / ".sean" / "state.json"
    if not state_path.exists():
        return None
    try:
        state = json.loads(state_path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        print(f"FAIL: state.json 解析失败: {exc}", file=sys.stderr)
        raise SystemExit(1)
    return (state.get("features") or {}).get(name)


def find_catalog(root: Path, feature: str) -> Path | None:
    d = root / "docs" / "artifacts"
    if not d.is_dir():
        return None
    exact = sorted(d.glob(f"*-{feature}.md"))
    if exact:
        return exact[-1]
    loose = [f for f in sorted(d.glob("*.md")) if feature in f.stem]
    return loose[-1] if loose else None


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _flag(value: str) -> bool:
    return value.strip().lower() in ("✅", "yes", "true", "y", "done", "1")


def parse_catalog(catalog: Path) -> list[dict]:
    """按 `## <Type>` 分段解析；列序遵循 templates/artifacts.md。"""
    artifacts: list[dict] = []
    current: str | None = None
    for raw in catalog.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        section = re.match(r"^##+\s+(.+)$", line)
        if section:
            current = SECTION_TYPES.get(section.group(1).strip().lower())
            continue
        if not line.startswith("|") or current is None:
            continue
        cells = _cells(line)
        if len(cells) < 3:
            continue
        path_cell = cells[0].strip("`").strip()
        if not re.fullmatch(r"[^\s|]+\.\w+", path_cell) or not cells[1].isdigit():
            continue  # 跳过表头与分隔行
        artifacts.append({
            "path": path_cell,
            "type": current,
            "task_id": int(cells[1]),
            "status": cells[3] if len(cells) > 3 else "",
            "executed": _flag(cells[4]) if len(cells) > 4 else False,
            "verified": _flag(cells[5]) if len(cells) > 5 else False,
        })
    return artifacts


def has_reverse_reference(path: Path) -> bool:
    if not path.exists():
        return False
    try:
        head = path.read_text(encoding="utf-8", errors="replace")[:800]
    except OSError:
        return False
    return "Requirement:" in head or "Generated by: sean" in head or "Catalog:" in head


def collect_state_artifacts(feature: dict) -> list[dict]:
    out = []
    for task in feature.get("tasks") or []:
        for art in task.get("artifacts") or []:
            out.append({
                "path": art.get("path", ""),
                "type": art.get("type", ""),
                "task_id": task.get("id"),
                "status": art.get("status", "declared"),
                "executed": bool(art.get("executed")),
                "verified": bool(art.get("verified")),
            })
    return out


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description="校验产物 catalog 与 state 一致性")
    ap.add_argument("project_root")
    ap.add_argument("feature_name")
    ap.add_argument("--json", action="store_true")
    args = ap.parse_args(argv)

    root = Path(args.project_root).resolve()
    feature = load_feature(root, args.feature_name)
    if feature is None:
        print(f"FAIL: feature '{args.feature_name}' 不在 state 中（docs/.sean/）", file=sys.stderr)
        return 1

    state_arts = collect_state_artifacts(feature)
    catalog = find_catalog(root, args.feature_name)
    catalog_arts = parse_catalog(catalog) if catalog else []

    errors: list[str] = []
    warnings: list[str] = []

    if state_arts and not catalog:
        errors.append(f"state 声明了 {len(state_arts)} 个产物，但 catalog 缺失")
    if catalog and state_arts and not catalog_arts:
        errors.append("catalog 存在但解析不到任何产物（检查表头与 `## <Type>` 分段）")

    state_paths = {a["path"] for a in state_arts}
    catalog_paths = {a["path"] for a in catalog_arts}
    for p in sorted(state_paths - catalog_paths):
        errors.append(f"state 有但 catalog 无: {p}")
    for p in sorted(catalog_paths - state_paths):
        warnings.append(f"catalog 有但 state 无: {p}")

    by_path = {a["path"]: a for a in catalog_arts}
    rows = []
    for art in sorted(state_arts, key=lambda x: x["path"]):
        on_disk = (root / art["path"]).exists()
        ref_ok = has_reverse_reference(root / art["path"])
        mirror = by_path.get(art["path"])
        dim_ok = True
        if mirror:
            dim_ok = (mirror["executed"] == art["executed"]
                      and mirror["verified"] == art["verified"]
                      and mirror["status"].lower() == str(art["status"]).lower())
            if not dim_ok:
                errors.append(
                    f"三维不一致: {art['path']} "
                    f"(state: {art['status']}/{art['executed']}/{art['verified']} · "
                    f"catalog: {mirror['status']}/{mirror['executed']}/{mirror['verified']})"
                )
            if mirror["type"] != art["type"]:
                warnings.append(f"类型不一致: {art['path']} (state {art['type']} / catalog {mirror['type']})")
        if not on_disk:
            errors.append(f"文件不存在: {art['path']}")
        if on_disk and not ref_ok:
            warnings.append(f"缺少反向引用头: {art['path']}")
        rows.append({
            "path": art["path"], "type": art["type"], "task_id": art["task_id"],
            "disk": on_disk, "reverse_ref": ref_ok, "dimensions_match": dim_ok,
        })

    ok = not errors
    if args.json:
        print(json.dumps({
            "feature": args.feature_name,
            "catalog": str(catalog.relative_to(root)) if catalog else None,
            "artifacts": rows,
            "errors": errors,
            "warnings": warnings,
            "status": "pass" if ok else "fail",
        }, ensure_ascii=False, indent=2))
        return 0 if ok else 1

    print(f"=== Artifact Check: {args.feature_name} ===")
    print(f"  state artifacts  : {len(state_arts)}")
    print(f"  catalog          : {catalog.relative_to(root) if catalog else '(missing)'}")
    print(f"  catalog artifacts: {len(catalog_arts)}")
    print()
    if rows:
        print(f"{'Path':<46} {'Type':<9} {'Task':<5} {'Disk':<6} {'RefHdr':<7} {'3Dims':<6}")
        print("-" * 84)
        for r in rows:
            print(f"{r['path']:<46} {r['type']:<9} {r['task_id']:<5} "
                  f"{'OK' if r['disk'] else 'MISSING':<6} "
                  f"{'OK' if r['reverse_ref'] else 'MISSING':<7} "
                  f"{'OK' if r['dimensions_match'] else 'DIFF':<6}")
        print()
    for e in errors:
        print(f"  ✗ {e}")
    for w in warnings:
        print(f"  ⚠ {w}")
    print()
    print("PASS: catalog 与 state 一致" if ok else f"FAIL: {len(errors)} 个 error, {len(warnings)} 个 warning")
    return 0 if ok else 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

#!/usr/bin/env python3
"""
sean_artifact_check.py — 验证产物目录（catalog）与 state.json 的一致性。

用法:
  python sean_artifact_check.py <project_root> <feature_name>

检查:
  1. catalog 文件存在且格式正确
  2. state.json 的 artifacts[] 与 catalog 表格一致
  3. 每个产物文件真实存在于磁盘
  4. 每个产物文件头部有反向引用注释
  5. status / executed / verified 三个维度一致

退出码: 0 = 一致, 1 = 有冲突
"""

import argparse
import json
import re
import sys
from pathlib import Path


def parse_catalog(catalog_path) -> list[dict]:
    """Parse artifact catalog markdown into artifact records."""
    if not Path(catalog_path).exists():
        return []
    content = Path(catalog_path).read_text(encoding="utf-8")
    artifacts = []
    # Match table rows: | `path` | type | task_id | ... |
    # NOTE: use a raw string — "\|" in a normal string is an invalid escape
    # that Python collapses to "|", which would be parsed as alternation.
    row_pattern = re.compile(
        r'^\|\s*`([^`]+)`\s*\|\s*(database|batch|config)\s*\|\s*(\d+)\s*\|',
        re.MULTILINE,
    )
    for m in row_pattern.finditer(content):
        artifacts.append({
            "path": m.group(1),
            "type": m.group(2),
            "task_id": int(m.group(3)),
        })
    return artifacts


def check_reverse_reference(artifact_path: str) -> bool:
    """Check the artifact file carries a reverse-reference header."""
    p = Path(artifact_path)
    if not p.exists():
        return False
    try:
        head = p.read_text(encoding="utf-8", errors="replace")[:600]
    except Exception:
        return False
    return "Requirement:" in head or "Generated by: sean" in head


def main():
    parser = argparse.ArgumentParser(description="Verify artifact catalog vs state.json")
    parser.add_argument("project_root")
    parser.add_argument("feature_name")
    args = parser.parse_args()

    root = Path(args.project_root)
    state_path = root / "docs" / ".sean" / "state.json"
    if not state_path.exists():
        print(f"FAIL: state.json not found at {state_path}")
        sys.exit(1)

    state = json.loads(state_path.read_text(encoding="utf-8"))
    feature = state.get("features", {}).get(args.feature_name)
    if not feature:
        print(f"FAIL: feature '{args.feature_name}' not in state.json")
        sys.exit(1)

    # Collect artifacts from state
    state_artifacts = []
    for task in feature.get("tasks", []):
        for art in task.get("artifacts", []) or []:
            state_artifacts.append({
                "path": art["path"],
                "type": art["type"],
                "task_id": task["id"],
                "status": art.get("status", "declared"),
                "executed": art.get("executed", False),
                "verified": art.get("verified", False),
            })

    # Find the catalog
    catalog_path = None
    artifacts_dir = root / "docs" / "artifacts"
    if artifacts_dir.exists():
        for f in artifacts_dir.glob("*.md"):
            if args.feature_name in f.name:
                catalog_path = f
                break

    print(f"=== Artifact Check: {args.feature_name} ===")
    print(f"state.json artifacts: {len(state_artifacts)}")
    print(f"catalog: {catalog_path or '(missing)'}")

    errors = []
    warnings = []

    # Check 1: catalog exists if state has artifacts
    if state_artifacts and not catalog_path:
        errors.append(f"catalog missing but state.json declares {len(state_artifacts)} artifacts")

    # Check 2: catalog parseable
    catalog_artifacts = parse_catalog(catalog_path) if catalog_path else []
    print(f"catalog artifacts parsed: {len(catalog_artifacts)}")

    if len(catalog_artifacts) != len(state_artifacts):
        errors.append(
            f"catalog ({len(catalog_artifacts)}) != state.json ({len(state_artifacts)})"
        )

    # Check 3: paths match
    catalog_paths = {a["path"] for a in catalog_artifacts}
    state_paths = {a["path"] for a in state_artifacts}
    for p in state_paths - catalog_paths:
        errors.append(f"artifact in state.json but not in catalog: {p}")
    for p in catalog_paths - state_paths:
        warnings.append(f"artifact in catalog but not in state.json: {p}")

    # Check 4 & 5: each artifact exists on disk + has reverse reference
    print()
    print(f"{'Path':<50} {'Type':<10} {'Disk':<6} {'RefHdr':<7} {'Status':<9} {'Exec':<6} {'Ver':<5}")
    print("-" * 100)
    for art in sorted(state_artifacts, key=lambda x: x["path"]):
        disk = "OK" if (root / art["path"]).exists() else "MISSING"
        ref = "OK" if check_reverse_reference(str(root / art["path"])) else "MISSING"
        print(
            f"{art['path']:<50} {art['type']:<10} {disk:<6} {ref:<7} "
            f"{art['status']:<9} {str(art['executed']):<6} {str(art['verified']):<5}"
        )
        if disk == "MISSING":
            errors.append(f"artifact file missing on disk: {art['path']}")
        if ref == "MISSING":
            warnings.append(f"artifact missing reverse-reference header: {art['path']}")

    print()
    if errors:
        print(f"FAIL: {len(errors)} error(s)")
        for e in errors:
            print(f"  ✗ {e}")
    if warnings:
        print(f"{len(warnings)} warning(s):")
        for w in warnings:
            print(f"  ⚠ {w}")
    if not errors and not warnings:
        print("PASS: catalog and state.json are consistent")

    sys.exit(1 if errors else 0)


if __name__ == "__main__":
    main()
